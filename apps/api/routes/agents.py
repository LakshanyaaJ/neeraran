"""
Agent Endpoints Router — Phase 4
Exposes the core agent loop to the frontend:
- Cases, Case Details (Evidence, Why, Plan, Traces)
- Ranked Repair Queue
- Forecasts (7-day demand, 72-hour reserve)
- Active Plan & Human Approval Gates
- Traces & Audit Logs
"""
from fastapi import APIRouter, HTTPException, Header, Body, Path, Query
from typing import Dict, Any, List, Optional
from pydantic import BaseModel
from sqlmodel import Session, select, desc

from ..agents.orchestrator import orchestrator
from ..agents.schemas import PrioritizerWeights
from ..sim.engine import sim_engine
from ..db.database import engine, AuditLog, ApprovalItem

router = APIRouter(tags=["agents"])

class ApprovalDecisionPayload(BaseModel):
    decision: str # "approved" or "rejected"
    note: Optional[str] = ""

@router.get("/api/cases")
def get_cases():
    """Retrieve all active cases identified by the agents."""
    # Ensure at least one orchestrator cycle has run
    if not orchestrator.active_cases:
        state = sim_engine.get_state()
        orchestrator.run_cycle(state)
    return orchestrator.get_cases()

@router.get("/api/cases/{case_id}")
def get_case_detail(case_id: str = Path(...)):
    """Retrieve complete case dossier: evidence, reasoning Why text, plan, and trace."""
    case = orchestrator.get_case(case_id)
    if not case:
        raise HTTPException(status_code=404, detail=f"Case {case_id} not found.")
    
    # Filter traces relevant to this case
    relevant_traces = [t.model_dump() for t in orchestrator.traces]
    return {
        "case": case.model_dump(),
        "evidence": [e.model_dump() for e in case.evidence],
        "why": case.why_text,
        "plan": case.plan.model_dump() if case.plan else None,
        "traces": relevant_traces[-7:] # Latest agent run
    }

@router.get("/api/queue")
def get_ranked_repair_queue():
    """Retrieve prioritizer's ranked repair queue with transparent score breakdowns."""
    if not orchestrator.active_cases:
        state = sim_engine.get_state()
        orchestrator.run_cycle(state)
