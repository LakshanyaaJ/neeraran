@router.post("/api/approvals/{approval_id}")
def decide_approval(
    approval_id: str = Path(...),
    payload: ApprovalDecisionPayload = Body(...),
    x_user_role: Optional[str] = Header(None)
):
    """
    Approve or reject a pending intervention.
    ADMIN ONLY: Non-admin users receive HTTP 403 Forbidden.
    """
    if x_user_role != "admin":
        raise HTTPException(status_code=403, detail="Forbidden: Only Estate Admin can approve or reject interventions.")

    res = orchestrator.approve_action(
        approval_id=approval_id,
        decision=payload.decision,
        note=payload.note or "",
        role="admin"
    )

    if res.get("status") == "not_found":
        raise HTTPException(status_code=404, detail=res["message"])

    return res

@router.get("/api/audit")
def get_audit_logs(limit: int = Query(50, le=200)):
    """Retrieve chronologically ordered audit logs from simulated enterprise integrations."""
    with Session(engine) as session:
        logs = session.exec(select(AuditLog).order_by(desc(AuditLog.id)).limit(limit)).all()
        return logs

@router.get("/api/traces")
def get_agent_traces(limit: int = Query(50, le=200)):
    """Retrieve runtime execution traces and latency metrics for all 7 agents."""
    return orchestrator.traces[-limit:]

@router.post("/api/orchestrator/run")
def trigger_orchestrator_cycle(x_user_role: Optional[str] = Header(None)):
    """Manually trigger a full 7-agent cycle over latest telemetry."""
    state = sim_engine.get_state()
    res = orchestrator.run_cycle(state, actor_role=x_user_role or "agent")
    return res

@router.post("/api/prioritizer/weights")
def update_prioritizer_weights(
    weights: PrioritizerWeights = Body(...),
    x_user_role: Optional[str] = Header(None)
):
    """
    Update mathematical prioritizer weights.
    Admin-only operational setting.
    """
    if x_user_role != "admin":
        raise HTTPException(status_code=403, detail="Forbidden: Only Estate Admin can modify prioritizer weights.")
    
    orchestrator.set_prioritizer_weights(weights)
    # Re-score active cases
    state = sim_engine.get_state()
    orchestrator.prioritizer.run(list(orchestrator.active_cases.values()), state)
    return {
        "status": "ok",
        "weights": weights.model_dump(),
        "ranked_queue": orchestrator.get_ranked_queue()
    }

